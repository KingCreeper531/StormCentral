export type DotIcon = keyof typeof DOT_ICONS;

/** The dot icon for a weather icon name ("clear-day", "rainy-2-night", "severe-thunderstorm"…). */
export function dotIconFor(name: string): DotIcon {
  const night = name.endsWith("-night");
  if (name.startsWith("clear")) return night ? "moon" : "sun";
  if (name.startsWith("cloudy-")) return night ? "moon-cloud" : "sun-cloud";
  if (name === "cloudy") return "cloud";
  if (name.startsWith("fog") || name.startsWith("frost")) return "fog";
  if (name.startsWith("rainy-1")) return "drizzle";
  if (name.startsWith("rainy-3")) return "heavy-rain";
  if (name.startsWith("rainy")) return "rain";
  if (name.startsWith("snowy")) return "snow";
  if (name.includes("sleet")) return "sleet";
  if (name === "hail") return "hail";
  if (name.includes("thunder")) return "thunder";
  if (name === "wind") return "wind";
  return "cloud";
}

/** The dots of an icon as [column, row, accent] for drawing. */
export function dotsOf(icon: DotIcon): [number, number, boolean][] {
  const out: [number, number, boolean][] = [];
  DOT_ICONS[icon].forEach((row, y) => {
    for (let x = 0; x < row.length; x++) if (row[x] !== ".") out.push([x, y, row[x] === "r"]);
  });
  return out;
}
